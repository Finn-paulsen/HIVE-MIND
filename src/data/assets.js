/**
 * @param {Record<string, any>} loc
 * @returns {Asset}
 */
export function normalizeLocation(loc) {
  const category = CATEGORY_MAP[loc?.type] || 'government';
  const [lat = 0, lon = 0] = Array.isArray(loc?.position) ? loc.position : [0, 0];
  const codeMatch = typeof loc?.description === 'string'
    ? loc.description.match(/\b([A-Z]{3,4})\b/g)
    : null;

  return {
    id: String(loc?.id || `${category}-${lat}-${lon}`),
    name: loc?.name || 'Unnamed Asset',
    category,
    coordinates: [Number(lat), Number(lon)],
    tags: [category, loc?.status || 'active', loc?.country || 'EU'].filter(Boolean),
    source: SOURCE_MAP[loc?.type] || 'Legacy Location Feed',
    updatedAt: loc?.history?.[loc.history.length - 1]?.timestamp || UPDATED_AT,
    confidence: loc?.status === 'critical' ? DEFAULT_CONFIDENCE_CRITICAL : DEFAULT_CONFIDENCE_ACTIVE,
    description: loc?.description || '',
    status: loc?.status || 'active',
    codes: loc?.type === 'airport'
      ? {
          iata: codeMatch?.find(code => code.length === 3),
          icao: codeMatch?.find(code => code.length === 4),
        }
      : undefined,
    country: loc?.country || 'DE',
  };
}
